// Generates the native design system from the shared sources, so iOS and Android never hand-type a
// colour, size or icon:
//   tokens.json → apps/ios/Padel/Design/Tokens.swift, apps/android/.../ui/theme/Tokens.kt
//   icons.ts    → apps/ios/Shared/Icons.xcassets (template SVGs), Android VectorDrawables
//   fonts/      → apps/ios/Shared/Fonts, Android res/font
// Run: npm run native -w @padel/design (also part of `make native-assets`).
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { ICONS, iconSvg, type IconName } from '../icons.ts';

const root = new URL('../../../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('packages/design/tokens.json', root), 'utf8'));
const HEADER = 'Generated by packages/design/scripts/export-native.ts from packages/design. Do not edit.';

const IOS = new URL('apps/ios/Padel/', root);
/** Compiled into the app and the widget extension. */
const IOS_SHARED = new URL('apps/ios/Shared/', root);
const ANDROID_RES = new URL('apps/android/app/src/main/res/', root);
const ANDROID_THEME = new URL('apps/android/app/src/main/java/app/americanoo/android/ui/theme/', root);

function write(url: URL, text: string) {
  mkdirSync(new URL('.', url), { recursive: true });
  writeFileSync(url, text);
}

const camel = (s: string) => s.replace(/[-_](\w)/g, (_, c: string) => c.toUpperCase());
const pascal = (s: string) => camel(s).replace(/^\w/, (c) => c.toUpperCase());
/** Swift/Kotlin identifiers can't start with a digit: "2xl" → "xl2". */
const ident = (s: string) => (/^\d/.test(s) ? s.replace(/^(\d+)(.*)$/, '$2$1') : camel(s));
const hex = (h: string) => h.replace('#', '').toUpperCase();

type Palette = Record<string, string>;
const light: Palette = tokens.color.light;
const dark: Palette = tokens.color.dark;
const state: Palette = tokens.color.state;

/* ------------------------------------------------------------------ */
/* Swift                                                                */
/* ------------------------------------------------------------------ */

function swift(): string {
  const rgb = (h: string) => {
    const n = parseInt(hex(h), 16);
    const c = (v: number) => +(v / 255).toFixed(4);
    return `red: ${c((n >> 16) & 255)}, green: ${c((n >> 8) & 255)}, blue: ${c(n & 255)}`;
  };
  const colors = Object.keys(light)
    .map((k) => `    static let ${camel(k)} = Color(light: UIColor(${rgb(light[k])}, alpha: 1), dark: UIColor(${rgb(dark[k])}, alpha: 1))`)
    .join('\n');
  const states = Object.entries(state)
    .map(([k, v]) => `    static let ${camel(k)} = Color(${rgb(v)})`)
    .join('\n');
  const radius = Object.entries(tokens.radius as Record<string, number>).map(([k, v]) => `        static let ${ident(k)}: CGFloat = ${v}`).join('\n');
  const space = (tokens.space as number[]).map((v, i) => `        static let s${i}: CGFloat = ${v}`).join('\n');
  const sizes = Object.entries(tokens.font.size as Record<string, number>).map(([k, v]) => `        static let ${ident(k)}: CGFloat = ${v}`).join('\n');

  return `// ${HEADER}
import SwiftUI
import UIKit

extension Color {
    /// Resolves per trait collection, so light/dark follow the system (and \`.preferredColorScheme\`).
    init(light: UIColor, dark: UIColor) {
        self.init(uiColor: UIColor { $0.userInterfaceStyle == .dark ? dark : light })
    }
}

/// Black & white, casual-professional. Colour only for functional state (PRD §3a).
enum Palette {
${colors}

    // Functional state only: rank movement and errors, always paired with an icon or text.
${states}
}

enum Tokens {
    enum Radius {
${radius}
    }

    /// Spacing scale: s0…s${tokens.space.length - 1} = ${tokens.space.join(', ')} pt.
    enum Space {
${space}
    }

    enum FontSize {
${sizes}
    }

    static let touchTarget: CGFloat = ${tokens.touchTarget}
    static let iconSize: CGFloat = ${tokens.icon.size}
    static let motionFast: Double = ${tokens.motion.fast / 1000}
    static let motionBase: Double = ${tokens.motion.base / 1000}
}

enum PadelFont {
    static let family = "${tokens.font.family}"
    static let mono = "${tokens.font.mono}"
}

/// Custom icon set (packages/design/icons.ts), template images in Shared/Icons.xcassets.
enum PadelIcon: String, CaseIterable {
${(Object.keys(ICONS) as IconName[]).map((n) => `    case ${camel(n)} = "icon-${n}"`).join('\n')}

    var image: Image { Image(rawValue) }
}
`;
}

