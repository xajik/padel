function iosAssets() {
  const catalog = new URL('Icons.xcassets/', IOS_SHARED);
  rmSync(catalog, { recursive: true, force: true });
  write(new URL('Contents.json', catalog), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
  for (const name of Object.keys(ICONS) as IconName[]) {
    const set = new URL(`icon-${name}.imageset/`, catalog);
    write(new URL(`${name}.svg`, set), iconSvg(name, 24, tokens.icon.stroke).replace(/currentColor/g, '#000000') + '\n');
    write(
      new URL('Contents.json', set),
      JSON.stringify(
        {
          images: [{ filename: `${name}.svg`, idiom: 'universal' }],
          info: { author: 'xcode', version: 1 },
          properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
        },
        null,
        2,
      ) + '\n',
    );
  }
}

function fonts() {
  const src = new URL('packages/design/fonts/', root);
  for (const [file, res] of [
    ['Geist.ttf', 'geist.ttf'],
    ['GeistMono.ttf', 'geist_mono.ttf'],
  ]) {
    mkdirSync(new URL('Fonts/', IOS_SHARED), { recursive: true });
    copyFileSync(new URL(file, src), new URL(`Fonts/${file}`, IOS_SHARED));
    mkdirSync(new URL('font/', ANDROID_RES), { recursive: true });
    copyFileSync(new URL(file, src), new URL(`font/${res}`, ANDROID_RES));
  }
}

write(new URL('Design/Tokens.swift', IOS), swift());
write(new URL('Tokens.kt', ANDROID_THEME), kotlin());
iosAssets();
for (const name of Object.keys(ICONS) as IconName[]) write(new URL(`drawable/ic_${name.replace(/-/g, '_')}.xml`, ANDROID_RES), vector(name));
fonts();
console.log(`Native design system: tokens, ${Object.keys(ICONS).length} icons and fonts → apps/ios, apps/android`);
