/* SVG → VectorDrawable                                                 */
/* ------------------------------------------------------------------ */

interface Node {
  tag: string;
  attrs: Record<string, string>;
  children: Node[];
}

function parse(markup: string): Node[] {
  const rootNode: Node = { tag: 'root', attrs: {}, children: [] };
  const stack = [rootNode];
  const re = /<(\/?)(\w+)([^>]*?)(\/?)>/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(markup))) {
    const [, closing, tag, rawAttrs, selfClosing] = m;
    if (closing) {
      stack.pop();
      continue;
    }
    const attrs: Record<string, string> = {};
    for (const a of rawAttrs.matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const node: Node = { tag, attrs, children: [] };
    stack[stack.length - 1].children.push(node);
    if (!selfClosing) stack.push(node);
  }
  return rootNode.children;
}

const n = (s: string | undefined, d = 0) => (s === undefined ? d : parseFloat(s));

function toPathData(node: Node): string {
  const a = node.attrs;
  switch (node.tag) {
    case 'path':
      return a.d;
    case 'circle': {
      const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
      return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0Z`;
    }
    case 'rect': {
      const [x, y, w, h] = [n(a.x), n(a.y), n(a.width), n(a.height)];
      const r = Math.min(n(a.rx), w / 2, h / 2);
      if (!r) return `M${x},${y}h${w}v${h}h${-w}Z`;
      return (
        `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0,1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0,1 ${-r},${r}` +
        `h${-(w - 2 * r)}a${r},${r} 0 0,1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0,1 ${r},${-r}Z`
      );
    }
    default:
      throw new Error(`Unsupported SVG element <${node.tag}>`);
  }
}

interface Style {
  fill: string;
  stroke: string;
  strokeWidth: number;
  opacity: number;
  fillOpacity: number;
  fillRule: string;
}

function vector(name: IconName): string {
  const out: string[] = [];
  const base: Style = { fill: 'none', stroke: 'currentColor', strokeWidth: tokens.icon.stroke, opacity: 1, fillOpacity: 1, fillRule: 'nonzero' };

  const walk = (nodes: Node[], inherited: Style, indent: string) => {
    for (const node of nodes) {
      const a = node.attrs;
      const s: Style = {
        fill: a.fill ?? inherited.fill,
        stroke: a.stroke ?? inherited.stroke,
        strokeWidth: n(a['stroke-width'], inherited.strokeWidth),
        opacity: inherited.opacity * n(a.opacity, 1),
        fillOpacity: n(a['fill-opacity'], inherited.fillOpacity),
        fillRule: a['fill-rule'] ?? inherited.fillRule,
      };
      if (node.tag === 'g') {
        const rot = a.transform?.match(/rotate\(([-\d.]+)\s+([-\d.]+)\s+([-\d.]+)\)/);
        out.push(`${indent}<group${rot ? ` android:rotation="${rot[1]}" android:pivotX="${rot[2]}" android:pivotY="${rot[3]}"` : ''}>`);
        walk(node.children, s, indent + '    ');
        out.push(`${indent}</group>`);
        continue;
      }
      const attrs = [`android:pathData="${toPathData(node)}"`];
      if (s.fill !== 'none') {
        attrs.push('android:fillColor="@android:color/white"');
        if (s.fillOpacity * s.opacity !== 1) attrs.push(`android:fillAlpha="${+(s.fillOpacity * s.opacity).toFixed(3)}"`);
        if (s.fillRule === 'evenodd') attrs.push('android:fillType="evenOdd"');
      }
      if (s.stroke !== 'none') {
        attrs.push(
          'android:strokeColor="@android:color/white"',
          `android:strokeWidth="${s.strokeWidth}"`,
          'android:strokeLineCap="round"',
          'android:strokeLineJoin="round"',
        );
        if (s.opacity !== 1) attrs.push(`android:strokeAlpha="${s.opacity}"`);
      }
      out.push(`${indent}<path\n${indent}    ${attrs.join(`\n${indent}    `)} />`);
    }
  };
  walk(parse(ICONS[name]), base, '    ');

  // White paths: Compose's Icon() tints them with LocalContentColor; the launcher shows them as-is.
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${out.join('\n')}
</vector>
`;
}

