/* Kotlin                                                               */
/* ------------------------------------------------------------------ */

function kotlin(): string {
  const col = (h: string) => `Color(0xFF${hex(h)})`;
  const scheme = (p: Palette) =>
    Object.keys(p)
      .map((k) => `    val ${camel(k)} = ${col(p[k])}`)
      .join('\n');
  return `// ${HEADER}
package app.americanoo.android.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import app.americanoo.android.R

/** Black & white, casual-professional. Colour only for functional state (PRD §3a). */
object LightPalette {
${scheme(light)}
}

object DarkPalette {
${scheme(dark)}
}

/** Functional state only: rank movement and errors, always paired with an icon or text. */
object StateColors {
${Object.entries(state).map(([k, v]) => `    val ${camel(k)} = ${col(v)}`).join('\n')}
}

object Radius {
${Object.entries(tokens.radius as Record<string, number>).map(([k, v]) => `    val ${ident(k)} = ${v}.dp`).join('\n')}
}

/** Spacing scale: s0…s${tokens.space.length - 1} = ${tokens.space.join(', ')} dp. */
object Space {
${(tokens.space as number[]).map((v, i) => `    val s${i} = ${v}.dp`).join('\n')}
}

object FontSize {
${Object.entries(tokens.font.size as Record<string, number>).map(([k, v]) => `    val ${ident(k)} = ${v}.sp`).join('\n')}
}

object Tokens {
    val touchTarget = ${tokens.touchTarget}.dp
    val iconSize = ${tokens.icon.size}.dp
    const val MOTION_FAST = ${tokens.motion.fast}
    const val MOTION_BASE = ${tokens.motion.base}
}

/** Custom icon set (packages/design/icons.ts) as VectorDrawables. */
enum class PadelIcon(val res: Int) {
${(Object.keys(ICONS) as IconName[]).map((n) => `    ${pascal(n)}(R.drawable.ic_${n.replace(/-/g, '_')}),`).join('\n')}
}
`;
}

